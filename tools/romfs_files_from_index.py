#!/usr/bin/env python3
"""Writes runtime/game_addresses/romfs_files.h from an extracted RomFS index.json (no 7.5 GB extraction needed).

Same table as tools/romfs_files.py, from build/extracted/romfs/index.json ({"files": [{"path", "size"}, ...]}):
a sorted list of FNV-1a 64 hashes of "<path>\\0<size>" with a version mask. This game is Skyward Sword HD
v1.0.0, so every file gets bit 0 (1.0.0/1.0.1 share the table; bits 1 is left clear).

  python3 tools/romfs_files_from_index.py build/extracted/romfs/index.json
"""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'runtime/game_addresses/romfs_files.h'
MASK = 1  # bit 0: 1.0.0


def fnv1a64(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('index', nargs='?', default='build/extracted/romfs/index.json')
    args = ap.parse_args()

    files = json.loads(Path(ROOT / args.index).read_text(encoding='utf-8'))['files']
    hashes = {}
    for f in files:
        rel, size = f['path'], int(f['size'])
        hashes[fnv1a64(rel.encode() + b'\0' + str(size).encode())] = MASK

    lines = [
        '// Generated by tools/romfs_files_from_index.py: the game version\'s RomFS files as FNV-1a 64 hashes of',
        '// "<path>\\0<size>", sorted, with the versions that have them (bit 0: 1.0.0). Do not edit.',
        '// %d entries; 1.0.0: %d files.' % (len(hashes), len(files)),
    ]
    lines += ['{0x%016xull, %d},' % (h, m) for h, m in sorted(hashes.items())]
    OUT.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    print('%s: %d entries (%d files)' % (OUT, len(hashes), len(files)))


if __name__ == '__main__':
    main()
