#!/usr/bin/env python3
"""Writes runtime/game_addresses/romfs_files.h: a sorted table of 64-bit hashes, one per RomFS file of the supported
Skyward Sword HD release, from the verified flat extraction in extracted/index.json. Only hashes and totals ship (no
file names, no game data).

Each hash is FNV-1a 64 over the file's path relative to romfs ("US/Object/en_US/0-Common.arc", '/' separators), a 0
byte, then its size in decimal ("684992"). Bit n is the n-th version of runtime/game_addresses/versions.h (bit 0 1.0.0,
bit 1 1.0.1: its index is the 1.0.1 update merged over the base by tools/extract.py). The
runtime and the start screen hash every file of a copy the same way (game_romfs_check_file in runtime/game_addresses.c)
and log the ones that aren't the game's.

  python3 tools/romfs_files.py [--index extracted/index.json] --index v1_0_1=<1.0.1 index.json>

Every version of versions.h needs an index (a bare path is v1_0_0's), so a regeneration never drops one.
"""
import argparse
import json
from pathlib import Path

from game_addresses import VERSIONS

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT/'runtime/game_addresses/romfs_files.h'
def fnv1a64(data: bytes) -> int:
    h = 0xcbf29ce484222325
    for b in data:
        h = ((h ^ b) * 0x100000001b3) & 0xffffffffffffffff
    return h

def entry_hash(rel: str, size: int) -> int:
    return fnv1a64(rel.encode() + b'\0' + str(size).encode())

def romfs_files(index: Path) -> dict:
    """{relative path: size} of every file in the verified extraction."""
    data = json.loads(index.read_text())
    assert data.get('status') == 'pass', f'{index}: not a verified extraction'
    files = {f['path']: f['size'] for f in data['files']}
    assert len(files) == len(data['files']), f'{index}: duplicate file paths'
    return files

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--index', action='append', default=[], metavar='[KEY=]PATH')
    args = ap.parse_args()
    indexes = {}
    for item in args.index or [str(ROOT/'extracted/index.json')]:
        key, sep, path = item.partition('=')
        key, path = (key, path) if sep and key in VERSIONS else ('v1_0_0', item)
        assert key not in indexes, f'two indexes for {key}'
        indexes[key] = Path(path)
    assert indexes.keys() == VERSIONS.keys(), f'needs an index for each of {", ".join(VERSIONS)}'
    masks, totals = {}, []
    for bit, (key, path) in enumerate((k, indexes[k]) for k in VERSIONS):
        files = romfs_files(path)
        assert files, f'no RomFS files in {path}'
        for rel, size in files.items():
            h = entry_hash(rel, size)
            masks[h] = masks.get(h, 0) | 1 << bit
        totals.append((key, len(files), sum(files.values())))
    assert all(m < 256 for m in masks.values()), 'more than 8 versions'
    summary = '; '.join(f'{k}: {n} files, {b} bytes' for k, n, b in totals)
    bs, nul = chr(92), chr(92) + '0'
    lines = ["// Generated by tools/romfs_files.py: every game version's RomFS files as FNV-1a 64 hashes of "
             f'"<path>{nul}<size>",',
             '// sorted, with the versions that have them (bit n: the n-th version of versions.h). Do not edit.',
             f'#define ROMFS_SS_VERSIONS {bs}']
    lines += [f'    X({key}, {n}, {size}ull) {bs}' for key, n, size in totals]
    lines[-1] = lines[-1][:-2]
    lines.append(f'// {len(masks)} entries; {summary}.')
    lines += [f'{{0x{h:016x}ull, {m}}},' for h, m in sorted(masks.items())]
    OUT.write_text(chr(10).join(lines) + chr(10))
    print(f'{OUT.relative_to(ROOT)}: {len(masks)} entries; {summary}')

if __name__ == '__main__':
    main()
